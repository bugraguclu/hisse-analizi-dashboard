export type StockKey = keyof typeof dict;
export type StockVars = Record<string, string | number>;

function interpolate(template: string, vars?: StockVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function stockText(key: StockKey, locale: Locale, vars?: StockVars): string {
  const entry: Entry = dict[key];
  return interpolate(entry[locale] ?? entry.tr, vars);
}
